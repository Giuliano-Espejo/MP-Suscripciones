CREATE TABLE plans (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(120)  NOT NULL,
    description           VARCHAR(500),
    tier                  VARCHAR(20)   NOT NULL,
    price                 NUMERIC(12,2) NOT NULL,
    currency              VARCHAR(3)    NOT NULL,
    monthly_hours         INT           NOT NULL,
    min_permanence_months INT           NOT NULL,
    active                BOOLEAN       NOT NULL,
    gateway_plan_id       VARCHAR(100),
    gateway_init_point    VARCHAR(500),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE plan_benefits (
    plan_id    BIGINT       NOT NULL REFERENCES plans (id) ON DELETE CASCADE,
    sort_order INT          NOT NULL,
    benefit    VARCHAR(200) NOT NULL,
    PRIMARY KEY (plan_id, sort_order)
);

CREATE TABLE promotions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(120) NOT NULL,
    valid_from       DATE         NOT NULL,
    valid_to         DATE         NOT NULL,
    discount_percent NUMERIC(5,2) NOT NULL,
    duration_months  INT          NOT NULL,
    active           BOOLEAN      NOT NULL
);

CREATE TABLE members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(150) NOT NULL,
    email      VARCHAR(150) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE subscriptions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id             BIGINT        NOT NULL REFERENCES members (id),
    plan_id               BIGINT        NOT NULL REFERENCES plans (id),
    status                VARCHAR(20)   NOT NULL,
    amount                NUMERIC(12,2) NOT NULL,
    promotion_id          BIGINT REFERENCES promotions (id),
    promo_active          BOOLEAN       NOT NULL,
    promo_ends_on         DATE,
    start_date            DATE,
    min_end_date          DATE,
    scheduled_cancel_date DATE,
    cancelled_at          DATE,
    gateway_id            VARCHAR(100) UNIQUE,
    init_point            VARCHAR(500),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_subscriptions_status ON subscriptions (status);

CREATE TABLE consumptions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT       NOT NULL REFERENCES subscriptions (id),
    consumed_on     DATE         NOT NULL,
    hours           NUMERIC(6,2) NOT NULL,
    description     VARCHAR(200),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_consumptions_subscription ON consumptions (subscription_id, consumed_on);

